#!/usr/bin/env python3
"""Generate a skeleton FHIR catalog for the MII systemic-therapy protocols.

Source of truth: the vendored MII CodeSystem
  scripts/mii-cs-onko-systemische-therapie-protokolle.json  (v2026.0.3, 164 codes)

The CodeSystem's `definition` field lists each protocol's component substances
(e.g. ABVD -> "Bleomycin, Dacarbazin, Doxorubicin, Vinblastin"). We use that as the
template to emit, per protocol:

  * PlanDefinition          — one per protocol, one action per component drug
  * ActivityDefinition      — one per (protocol, component) "sig" (draft, NO dose yet)
  * Medication              — one per distinct substance (deduped)

Doses / cycle timing are intentionally absent: MII carries only the drug list, not
the dosing. Executable dose content is derived from HemOnc in a later phase and
merged onto the matched protocols (oncoreg-o23 / -d47).

Outputs (input/fsh/):
  Medication-mii-substanzen.fsh
  ActivityDefinition-mii-protokoll-sigs.fsh
  PlanDefinition-mii-protokolle.fsh
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
CS_PATH = HERE / "mii-cs-onko-systemische-therapie-protokolle.json"
FSH = REPO / "input" / "fsh"

MII_CS = ("https://www.medizininformatik-initiative.de/fhir/ext/modul-onko/"
          "CodeSystem/mii-cs-onko-systemische-therapie-protokolle")
PD_TYPE = "http://terminology.hl7.org/CodeSystem/plan-definition-type"

_TRANS = str.maketrans({
    "ä": "ae", "ö": "oe", "ü": "ue", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue", "ß": "ss",
    "é": "e", "è": "e", "ê": "e", "á": "a", "à": "a", "í": "i", "ó": "o", "ú": "u",
    "ñ": "n", "ç": "c",
})


def slug(s: str) -> str:
    s = s.translate(_TRANS)
    s = re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
    return s or "x"


def pascal(s: str) -> str:
    s = s.translate(_TRANS)
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", s) if p)


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def uniq(candidate: str, used: set) -> str:
    if candidate not in used:
        used.add(candidate); return candidate
    n = 2
    while f"{candidate}-{n}" in used:
        n += 1
    out = f"{candidate}-{n}"; used.add(out); return out


def main() -> None:
    cs = json.loads(CS_PATH.read_text(encoding="utf-8"))
    version = cs.get("version", "unknown")
    concepts = cs.get("concept", [])

    banner = [
        "// AUTO-GENERATED by scripts/gen_mii_protocol_stubs.py — DO NOT EDIT BY HAND.",
        f"// Source: MII CodeSystem systemische-therapie-protokolle v{version} "
        f"({len(concepts)} protocols).",
        "// Skeleton (status=draft): drug components only, no doses (doses come from HemOnc later).",
        "",
    ]
    pd_out, ad_out, mk_out = list(banner), list(banner), list(banner)

    drug_slug = {}          # display -> slug (dedup Medication)
    used_ids = set()
    n_pd = n_ad = 0

    for c in concepts:
        code = c["code"]
        display = c.get("display", code)
        definition = (c.get("definition") or "").strip()
        components = [d.strip() for d in definition.split(",") if d.strip()] if definition else []

        pid = uniq(f"mii-protokoll-{slug(code)}", used_ids)
        n_pd += 1
        pd = [
            f"Instance: {pid}",
            "InstanceOf: PlanDefinition",
            "Usage: #definition",
            f'* name = "MiiProtokoll{pascal(code)}"',
            f'* title = "{esc(display)} — MII Onkologie systemic-therapy protocol (skeleton)"',
            "* status = #draft",
            "* experimental = true",
            f'* version = "{version}"',
            f"* type = {PD_TYPE}#clinical-protocol",
            "* identifier[0].use = #official",
            f'* identifier[0].system = "{MII_CS}"',
            f'* identifier[0].value = "{esc(code)}"',
            f'* description = "Skeleton PlanDefinition for MII protocol \'{esc(code)}\' '
            f'({len(components)} component drugs from the MII definition). Doses/timing to be '
            f'derived from HemOnc. status=draft."',
        ]

        for drug in components:
            # Medication (deduped per distinct drug)
            if drug not in drug_slug:
                dslug = uniq(f"mii-drug-{slug(drug)}", used_ids)
                drug_slug[drug] = dslug
                mk_out += [
                    f"Instance: {dslug}",
                    "InstanceOf: Medication",
                    "Usage: #definition",
                    f'* code.text = "{esc(drug)}"',
                    "* status = #active",
                    '* extension[http://hl7.org/fhir/StructureDefinition/artifact-description].valueMarkdown = '
                    f'"Skeleton Medication for substance \'{esc(drug)}\' '
                    f'(MII systemic-therapy substance). ATC/RxNorm coding to be added from HemOnc."',
                    "",
                ]
            dslug = drug_slug[drug]

            # ActivityDefinition — one sig per (protocol, drug), no dose yet
            sid = uniq(f"mii-sig-{slug(code)}-{slug(drug)}", used_ids)
            n_ad += 1
            ad_out += [
                f"Instance: {sid}",
                "InstanceOf: ActivityDefinition",
                "Usage: #definition",
                f'* name = "MiiSig{pascal(code)}{pascal(drug)}"',
                f'* title = "{esc(drug)} in {esc(code)} (skeleton sig)"',
                "* status = #draft",
                "* experimental = true",
                f'* version = "{version}"',
                "* kind = #MedicationRequest",
                f"* productReference = Reference({dslug})",
                f'* description = "Skeleton sig: {esc(drug)} as a component of MII protocol '
                f'\'{esc(code)}\'. Dose/route/schedule to be derived from HemOnc. status=draft."',
                "",
            ]

            # wire the action into the PlanDefinition
            pd += [
                f'* action[+].title = "{esc(drug)}"',
                f"* action[=].definitionCanonical = Canonical({sid})",
            ]

        pd.append("")
        pd_out += pd

    FSH.mkdir(parents=True, exist_ok=True)
    (FSH / "Medication-mii-substanzen.fsh").write_text("\n".join(mk_out), encoding="utf-8")
    (FSH / "ActivityDefinition-mii-protokoll-sigs.fsh").write_text("\n".join(ad_out), encoding="utf-8")
    (FSH / "PlanDefinition-mii-protokolle.fsh").write_text("\n".join(pd_out), encoding="utf-8")

    print(f"PlanDefinition   : {n_pd}")
    print(f"ActivityDefinition: {n_ad}")
    print(f"Medication: {len(drug_slug)}")


if __name__ == "__main__":
    main()
